<?php

/*
|--------------------------------------------------------------------------
| Request Logs Table
|--------------------------------------------------------------------------
|
| Converts database logs into structured
| table rows for the shared table component.
|
*/

$rows = [];

/*
|--------------------------------------------------------------------------
| Empty State
|--------------------------------------------------------------------------
*/

if (empty($db_logs)){

    echo APIPlatform_Renderer::component(

        'alert',

        [

            'type' => 'info',

            'content' => 'No requests yet.'
        ]
    );

    return;
}

/*
|--------------------------------------------------------------------------
| Build Table Rows
|--------------------------------------------------------------------------
*/

foreach($db_logs as $log){

    $rows[] = [

        /*
        |--------------------------------------------------------------------------
        | Time
        |--------------------------------------------------------------------------
        */

        esc_html(
            $log->created_at
        ),

        /*
        |--------------------------------------------------------------------------
        | API Endpoint
        |--------------------------------------------------------------------------
        */

        esc_html(
            $log->endpoint
        ),

        /*
        |--------------------------------------------------------------------------
        | Status
        |--------------------------------------------------------------------------
        */

        esc_html(
            $log->status
        ),

        /*
        |--------------------------------------------------------------------------
        | IP Address
        |--------------------------------------------------------------------------
        */

        esc_html(
            $log->ip
        ),

        /*
        |--------------------------------------------------------------------------
        | Response Time
        |--------------------------------------------------------------------------
        */

        esc_html(
            $log->response_time
        )
    ];
}

/*
|--------------------------------------------------------------------------
| Render Card + Table
|--------------------------------------------------------------------------
*/

$content = APIPlatform_Renderer::component(

    'table',

    [

        'headers' => [

            'Time',
            'API',
            'Status',
            'IP',
            'Time (s)'
        ],

        'rows' => $rows
    ]
);

/*
|--------------------------------------------------------------------------
| Final Card Render
|--------------------------------------------------------------------------
*/

echo APIPlatform_Renderer::component(

    'card',

    [

        'title' => 'Recent Requests',

        'content' => $content
    ]
);
?>